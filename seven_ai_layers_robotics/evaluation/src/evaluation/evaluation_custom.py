from flask import request, jsonify, Blueprint

from recipe_recommendation.recipe_recommendation import calculate_recipe
from mechanistic_reasoning.mechanistic_reasoning import calculate_mechanistic_reasoning
import sys
from pathlib import Path
sys.path.append(str(Path(__file__).resolve().parents[3]))
from seven_ai_layers_robotics.config import config

evaluation_custom_bp = Blueprint('evaluation_custom', __name__)


def get_required_params(data: dict) -> tuple[dict, dict, str, any, any, dict]:
    '''
    Get input params of 'evaluation custom' from Report.

    Args:
         data: Report transformed.

    Returns:
        optimize (Optimized recipe), control (Control recipe), to_evaluate (Recipe optimization suggestions generated by language model),
        substance (Compound description in supporting information), ground (Reference text for comparison), indicator_weight (Indicator weights).
    '''

    optimize = data.get("optimized_FP", {})
    control = data.get("control_FP", {})

    indicator_weight = data["evaluation_custom"].get("indicator_weight", None)

    to_evaluate = data.get("mechanism", "")
    substance = data.get("substance", None)
    ground = data.get("ground", None)

    return optimize, control, to_evaluate, substance, ground, indicator_weight



@evaluation_custom_bp.route('/evaluation_custom', methods=['POST'])
def evaluation_custom():
    data = request.get_json()
    optimize, control, to_evaluate, substance, ground, indicator_weight = get_required_params(data)

    result = calculate_evaluation_custom(optimize, control, to_evaluate, substance, ground, indicator_weight)

    return jsonify(result)

def calculate_evaluation_custom(
    optimize: dict,
    control: dict,
    to_evaluate: str,
    substance: str = None,
    ground: str = None,
    indicator_weight: dict = None
) -> dict:
    '''
    Calculate evaluation layer score based on indicators and weights.

    Args:
        optimize: Optimized recipe.
        control: Control recipe.
        to_evaluate: Recipe optimization suggestions generated by language model.
        substance: Compound description in supporting information.
        ground: Reference text for comparison.
        indicator_weight: Indicator weights.

    Returns:
        Custom evaluation layer score.
    '''

    if indicator_weight is None:
        indicator_weight = config.evaluation.indicator_weight

    recipe_integrity_weight = indicator_weight.get("recipe_integrity", 0)
    formula_rationality_weight = indicator_weight.get("formula_rationality", 0)
    parameter_rationality_weight = indicator_weight.get("parameter_rationality", 0)
    performance_rationality_weight = indicator_weight.get("performance_rationality", 0)
    recipe_recommendation_weight = indicator_weight.get("recipe_recommendation", 0)
    experimental_validation_weight = indicator_weight.get("experimental_validation", 0)
    domain_knowledge_weight = indicator_weight.get("domain_knowledge", 0)
    mechanism_integrity_weight = indicator_weight.get("mechanism_integrity", 0)
    mechanism_interpretation_weight = indicator_weight.get("mechanism_interpretation", 0)
    mechanism_comprehensiveness_weight = indicator_weight.get("mechanism_comprehensiveness", 0)
    mechanism_coherence_weight = indicator_weight.get("mechanism_coherence", 0)

    valid_weights = [
        0 <= recipe_integrity_weight <= 1,
        0 <= formula_rationality_weight <= 1,
        0 <= parameter_rationality_weight <= 1,
        0 <= performance_rationality_weight <= 1,
        0 <= recipe_recommendation_weight <= 1,
        0 <= experimental_validation_weight <= 1,
        0 <= domain_knowledge_weight <= 1,
        0 <= mechanism_integrity_weight <= 1,
        0 <= mechanism_interpretation_weight <= 1,
        0 <= mechanism_comprehensiveness_weight <= 1,
        0 <= mechanism_coherence_weight <= 1
    ]
    weights = sum(valid_weights)

    recipe_weight = recipe_integrity_weight + formula_rationality_weight + parameter_rationality_weight + performance_rationality_weight + recipe_recommendation_weight + experimental_validation_weight
    mechanism_weight = domain_knowledge_weight + mechanism_integrity_weight + mechanism_interpretation_weight + mechanism_comprehensiveness_weight + mechanism_coherence_weight

    if abs(recipe_weight + mechanism_weight - 1) > 1e-10 or weights != 11:
        return {
            "reason": "The weights must sum to 1 and each weight must lie in the interval [0, 1].",
            "score": None
        }

    recipe_results = calculate_recipe(optimize, control)
    mechanism_results = calculate_mechanistic_reasoning(to_evaluate, substance, ground)

    try:
        recipe_score = 0
        for key, item in recipe_results.items():
            if key in config.evaluation.recipe_custom + config.evaluation.mechanism_custom:
                recipe_score += indicator_weight.get(key, 0) * item.get("score", 0)
    except Exception as e:
        print("recipe_error", e)
        recipe_score = None

    try:
        mechanism_score = 0
        for key, item in mechanism_results.items():
            if key in config.evaluation.recipe_custom + config.evaluation.mechanism_custom:
                mechanism_score += indicator_weight.get(key, 0) * item.get("score", 0)
    except Exception as e:
        print("mechanism_error", e)
        mechanism_score = None

    try:
        total_score = recipe_score + mechanism_score
    except Exception as e:
        print("total_error", e)
        total_score = None

    detail = {
        "Recipe_Recommendation": recipe_results,
        "Mechanistic_Reasoning": mechanism_results
    }

    result = {
        "reason": detail,
        "score": {
            "Recipe_Recommendation": recipe_score,
            "Mechanistic_Reasoning": mechanism_score,
            "overall": total_score
        }
    }

    return result
