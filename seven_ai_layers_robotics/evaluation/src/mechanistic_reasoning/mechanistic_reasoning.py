def build_user_prompt(rubric_dict: Dict[str, Any], sample_str: str) -> str:


    rubric_str = json.dumps(rubric_dict, ensure_ascii=False, indent=2)
    answer_str = sample_str  # json.dumps(sample_dict, ensure_ascii=False, indent=2)

    schema_example = {
        "mechanistic_reasoning": {
            "overall_score": 0,
            "dimensions": [
                {
                    "id": 1,
                    "name_zh": "placeholder",
                    "name_en": "placeholder",
                    "score": 0,
                    "comment": "placeholder"
                }
            ]
        }
    }
    schema_str = json.dumps(schema_example, ensure_ascii=False, indent=2)

    prompt = f"""
You will grade a model-generated perovskite-solar-cell report using the rubric below.

RUBRIC_JSON:
{rubric_str}

MODEL_ANSWER_JSON:
{answer_str}

Grading instructions:

1. The rubric JSON has two top-level keys:
   - "recipe_recommendation"
   - "mechanistic_reasoning"

   Note: Although the rubric contains two sections, only the 'mechanistic reasoning' part will be graded this time.

2. For each of these, the field "dimensions" is a list of dimension objects with fields:
   - id
   - name_zh
   - name_en
   - focus


3. For EVERY dimension inside each rubric:
   - Add a new field "score" (integer from 0 to max_score, inclusive).
   - Add a new field "comment" (1–2 English sentences explaining the score).

4. When building your output:
   - ONLY add "score" and "comment" fields; do not modify existing fields.

5. For "mechanistic_reasoning" rubric:
   - Add an "overall_score" field equal to the sum of all its dimension scores.

6. Output format:
   - Return ONE single JSON object with exactly only one top-level keys:
     "mechanistic_reasoning".
   - The JSON structure should follow this example shape (field names, not values):
{schema_str}

7. IMPORTANT:
   - Do NOT include markdown backticks.
   - Do NOT add any explanatory text before or after the JSON.
"""
    return prompt


def score_one_sample(sample: str, rubric: Dict[str, Any]) -> Dict[str, Any]:
    user_prompt = build_user_prompt(rubric, sample)
    answer, reasoning = get_answer_and_thinking(SYSTEM_PROMPT, user_prompt)

    raw = answer.strip()

    if "<think>" in raw and "</think>" in raw:
        think_end = raw.find("</think>") + len("</think>")
        raw = raw[think_end:].strip()
    
    # Step 2: Try to extract from markdown code blocks
    if raw.startswith("```"):
        raw = raw.strip("`")
        if "\n" in raw:
            raw = raw.split("\n", 1)[1]
        if raw.endswith("```"):
            raw = raw.rsplit("```", 1)[0]
        raw = raw.strip()
    
    # Step 3: If still not starting with { or [, find the first JSON object
    if not (raw.startswith("{") or raw.startswith("[")):
        # Find first { and last } to extract JSON
        start_idx = raw.find("{")
        end_idx = raw.rfind("}") + 1
        if start_idx != -1 and end_idx > start_idx:
            raw = raw[start_idx:end_idx]

    try:
        scores = json.loads(raw)
    except json.JSONDecodeError as e:
        print("JSON decode error, raw output:")
        print(raw)
        raise e

    return scores

