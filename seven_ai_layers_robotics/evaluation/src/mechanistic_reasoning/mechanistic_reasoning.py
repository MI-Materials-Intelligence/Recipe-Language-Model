def extract_content(text: str) -> Tuple[str, str]:
    """
    Compatible with DeepSeek and other models: extract content from <think> and <answer> tags in the text.
    Returns: (reasoning_content, answer_content).
    If no tags, returns ("", original text).
    """
    think_pattern = r'<think>(.*?)</think>'
    think_matches = re.findall(think_pattern, text, re.DOTALL)
    reasoning_content = ''.join(think_matches).strip()

    answer_pattern = r'<answer>(.*?)</answer>'
    answer_matches = re.findall(answer_pattern, text, re.DOTALL)
    answer_content = ''.join(answer_matches).strip()

    if not reasoning_content and not answer_content:
        return "", text.strip()
    return reasoning_content, answer_content


def get_answer_and_thinking(system_prompt: str, user_prompt: str) -> Tuple[str, str]:
    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_prompt},
    ]

    client = OpenAI(api_key=API_KEYS[LLM_KEY], base_url=BASE_URLS[LLM_KEY])

    result = client.chat.completions.create(
        messages=messages,
        model=LLM_MODELS[LLM_KEY],
        temperature=0.2,
        top_p=0.9,
        n=1,
        max_tokens=4096,
    )

    response = result.choices[0].message.content.strip()

    print("Model scoring output: ", response)

    # If there is no separate reasoning field, it is assumed here that you have implemented extract_content.
    reasoning, answer = extract_content(response)
    if not answer.strip():
        answer = response.strip()
    return answer, reasoning


