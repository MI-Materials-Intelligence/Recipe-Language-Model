def calculate_mechanistic_reasoning(to_evaluate: str, substance: str = None, ground: str = None) -> dict:
    '''Calculate mechanistic reasoning part scores in evaluation layer.

    Args:
        to_evaluate: Recipe optimization suggestions generated by language model.
        substance: Compound description in supporting information. Defaults to None.
        ground: Reference text for comparison. Defaults to None.

    Returns:
        Dictionary containing all mechanistic reasoning part scores.
    '''

    results = {}
    result_item = {}

    try:
        llm_results = llm_score(to_evaluate)

        dimension_data = llm_results.get("rubric_scores", {}).get("mechanistic_reasoning", {})
        dimensions_scores = dimension_data.get("dimensions", [])

        if not dimensions_scores:
            result_item = {
                "reason": "Failed to retrieve scoring dimension data",
                "score": None
            }
        results = result_item

        score_mapping = {item["id"]: item for item in dimensions_scores}

        for score_id in range(1, len(config.evaluation.mechanism_indicators) + 1):
            if score_id in score_mapping:
                item = score_mapping[score_id]
                results[config.evaluation.mechanism_indicators[score_id - 1]] = {
                    "reason": item.get("comment", "No comment"),
                    "score": item.get("score", 0) / 10.0
                }

                if score_id == 1:
                    if substance:
                        sub_score = get_terminology(substance)
                        llm_reason = results[config.evaluation.mechanism_indicators[score_id - 1]]["reason"]
                        llm_score_val = results[config.evaluation.mechanism_indicators[score_id - 1]]["score"]
                        results[config.evaluation.mechanism_indicators[score_id - 1]] = {
                            "reason": f"llm: {llm_reason}; substance: {sub_score}",
                            "score": SUBSTANCE_WEIGHT * sub_score + (1 - SUBSTANCE_WEIGHT) * llm_score_val,
                        }

        MECHANISM_FUNCTIONS = {
            "domain_knowledge": lambda: calculate_domain_knowledge(to_evaluate, substance, ground),
            "mechanism_integrity": lambda: calculate_mechanism_integrity(to_evaluate, ground),
            "mechanism_interpretation": lambda: calculate_mechanism_interpretation(to_evaluate, ground),
            "mechanism_comprehensiveness": lambda: calculate_mechanism_comprehensiveness(to_evaluate, ground),
            "mechanism_coherence": lambda: calculate_mechanism_coherence(to_evaluate, ground)
        }

        results = {k: results[k] for k in config.evaluation.mechanism_custom if k in results}

        for key, func in MECHANISM_FUNCTIONS.items():
            if key in results and results.get(key, {}).get("score") is None:
                results[key] = func()

    except Exception as e:
        error_msg = f"Scoring failed: {str(e)}..."
        for i in range(1, len(config.evaluation.mechanism_indicators) + 1):
            results[config.evaluation.mechanism_indicators[i - 1]] = {
                "reason": error_msg,
                "score": None
            }

    return results

