## rule
def extract_with_pattern(data, pattern=r".+"):
    """
    Use regular expressions to extract strings matching a specific pattern
    :param data: Input data
    :param pattern: Regular expression pattern
    :return: Concatenation of matched results
    """
    matches = []

    def _scan(obj):
        if isinstance(obj, str) and re.match(pattern, obj):
            matches.append(obj)
        elif isinstance(obj, dict):
            for v in obj.values():
                _scan(v)
        elif isinstance(obj, (list, tuple)):
            for item in obj:
                _scan(item)

    _scan(data)
    return " ".join(matches)

def get_similarity(pred_text, ground_text, config={"history_mean": 0.4, "calculator": None, "penalty": None}):
    match_score = config["history_mean"]
    calculator = config["calculator"]
    penalty = config["penalty"]

    if calculator is None:
        calculator = TfidfVectorizer(stop_words='english', max_features=8)

    if isinstance(pred_text, dict):
        pred_text = extract_with_pattern(pred_text)
    if isinstance(ground_text, dict):
        ground_text = extract_with_pattern(ground_text)

    if "none" not in ground_text.lower():
        try:
            vectors = calculator.fit_transform([pred_text, ground_text])
            similarity = cosine_similarity(vectors[0], vectors[1])
            match_score = similarity[0][0]

            if penalty != None:
                match_score *= penalty

        except:
            print("Warning: error in Content")

    return {
        "reason": f"Similarity is {match_score:.2f}.",
        "score": float(match_score),
    }


def get_terminology(text, config={"material_dict": material_dict, "default_value": 0}):
    match_score = config["default_value"]

    if isinstance(text, dict):
        text = extract_with_pattern(text)

    for mat_short, mat_long in config["material_dict"].items():
        match_short = re.search(mat_short.strip().lower(), text.strip().lower())

        if match_short:
            match_score = 0.4

            match_long = re.search(mat_long.strip().lower(), text.strip().lower())

            if match_long:
                match_score = 1
        else:
            pass

    return match_score


def get_structure(text, config={"min_length": 200}):
    if not isinstance(text, str):
        print(f"Warning: Structure not is a string {text}")
    if isinstance(text, dict):
        text = extract_with_pattern(text)

    if len(text) > config["min_length"]:
        score = 1
    else:
        score = 0

    return {
        "reason": "",
        "score": score,
    }

